import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createCountWriteTracker, affectsCounts } from './countWriteTracker.js';
test('mirrors count mutation funnel without tracking observations or message body reads', () => {
  for (const path of ['/mail/messages/id/read', '/mail/messages/bulk-read', '/mail/mark-all-read', '/mail/messages/bulk-archive', '/mail/messages/id', '/mail/folders/empty', '/gtd/classify', '/gtd/classify/undo', '/gtd/done']) assert.equal(affectsCounts('POST', path), true);
  for (const path of ['/mail/counts/refresh', '/mail/unread-counts', '/mail/messages/id/body']) assert.equal(affectsCounts('GET', path), false);
  assert.equal(affectsCounts('POST', '/mail/counts/refresh'), false);
});
test('only current-session idle requests a fence; new writes invalidate its version', async () => {
  let generation = 1, release;
  const starts = [], idle = [];
  const tracker = createCountWriteTracker({ loadLease: async () => ({ lease: { token: 'tracker.test.1', expiresInMs: 360000 } }), generation: () => generation, start: event => starts.push(event), idle: event => idle.push(event) });
  const held = tracker.track('PATCH', '/mail/messages/id/read', () => new Promise(resolve => { release = resolve; }));
  await tracker.track('POST', '/mail/messages/bulk-archive', async () => ({}));
  assert.equal(idle.length, 0);
  release(); await held;
  assert.equal(idle.length, 1);
  assert.equal(idle[0].version, 2);
  const failed = tracker.track('PATCH', '/mail/messages/id/read', async () => { throw new Error('network'); });
  await assert.rejects(failed);
  assert.equal(idle.at(-1).version, 3, 'uncertain failure still requests provider observation, never a success barrier');
  let oldRelease;
  const old = tracker.track('PATCH', '/mail/messages/id/read', () => new Promise(resolve => { oldRelease = resolve; }));
  for (let i = 0; i < 10 && !oldRelease; i++) await Promise.resolve();
  assert.equal(typeof oldRelease, 'function');
  generation++;
  oldRelease(); await old;
  assert.equal(idle.length, 2, 'old completion cannot request a fence for a new session');
  assert.equal(starts.length, 4);
});
test('local Undo and async-resolution intents block certification across unrelated completed requests', async () => {
  const idle = [], starts = [];
  const tracker = createCountWriteTracker({ generation: () => 1, loadLease: async () => ({ lease: { token: 'intent.test.1', expiresInMs: 360000 } }), start: e => starts.push(e), idle: e => idle.push(e) });
  const endUndo = tracker.beginIntent(), endResolution = tracker.beginIntent();
  await tracker.track('PATCH', '/mail/messages/id/read', async () => ({}));
  assert.equal(idle.length, 0, 'HTTP idle cannot certify a future deferred provider write');
  assert.equal(tracker.inspect().inFlight, 0);
  assert.equal(tracker.inspect().localIntents, 2);
  endUndo(); endUndo();
  assert.equal(tracker.inspect().localIntents, 1, 'Undo/double cleanup owns one intent only');
  assert.equal(idle.length, 0);
  endResolution();
  assert.equal(idle.length, 1);
  assert.equal(idle[0].localIntents, 0);
  assert.equal(idle[0].version, 3);
  assert.equal(starts.length, 3);
});
test('a newly begun intent invalidates a requested certificate, and old-session cleanup cannot affect the new session', async () => {
  let generation = 1;
  const idle = [];
  const tracker = createCountWriteTracker({ generation: () => generation, loadLease: async () => ({ lease: { token: 'intent.test.1', expiresInMs: 360000 } }), start() {}, idle: e => idle.push(e) });
  await tracker.track('PATCH', '/mail/messages/id/read', async () => ({}));
  const requestedVersion = idle[0].version;
  const end = tracker.beginIntent();
  tracker.acknowledge(requestedVersion);
  assert.equal(tracker.inspect().opIds.length, 1, 'a certificate predating the intent cannot discard uncertain IDs');
  assert.ok(tracker.inspect().version > requestedVersion);
  generation++;
  assert.equal(tracker.inspect().localIntents, 0);
  assert.equal(tracker.inspect().version, 0);
  const endCurrent = tracker.beginIntent();
  end(); end();
  assert.equal(tracker.inspect().localIntents, 1);
  assert.equal(idle.length, 1, 'old end cannot trigger current-session refresh');
  endCurrent(); endCurrent();
  assert.equal(idle.length, 2);
  assert.equal(tracker.inspect().localIntents, 0);
});
